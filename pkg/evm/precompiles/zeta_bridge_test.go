package precompiles

import (
        "testing"
)

func TestZetaBridgeE2E(t *testing.T) {
        zb := &ZetaBridge{}

        // DATA SYNCED WITH SUCCESSFUL RUST KERNEL BATCH TEST
        // We are testing a batch of 1 for now to ensure backward compatibility,
        // but the structure now supports N signatures.
        input := []byte{
                // 1. Batch Count (1 byte) -> 0x01
                0x01,

                // 2. PubKey Batch (32 bytes * 1)
                0x3b, 0x6a, 0x27, 0xbc, 0xce, 0xb6, 0xa4, 0x2d, 0x62, 0xa3, 0xa8, 0xd0, 0x2a, 0x6f, 0x0d, 0x73,
                0x65, 0x32, 0x15, 0x77, 0x1d, 0xe2, 0x43, 0xa6, 0x3a, 0xc0, 0x48, 0xa1, 0x8b, 0x59, 0xda, 0x29,

                // 3. Signature Batch (64 bytes * 1)
                0x2a, 0x2b, 0x86, 0x9a, 0x2f, 0x6b, 0x29, 0xcd, 0x63, 0x70, 0xaa, 0xbd, 0x6b, 0xbb, 0x70, 0x09,
                0xff, 0x42, 0x0f, 0xce, 0x68, 0x61, 0x15, 0xa9, 0x0f, 0x72, 0x39, 0x12, 0x87, 0x2f, 0xee, 0x4b,
                0x4b, 0x9f, 0xa1, 0x16, 0x47, 0x0c, 0x8c, 0x3d, 0x70, 0x22, 0x47, 0xaf, 0xa8, 0x10, 0x2f, 0xfe,
                0xfb, 0x73, 0xf6, 0x3f, 0xb4, 0xc8, 0xef, 0x16, 0x3f, 0x32, 0xd8, 0x69, 0x9f, 0xda, 0xe8, 0x02,

                // 4. Msg: "Kin" (Remaining bytes)
                0x4b, 0x69, 0x6e,
        }

        out, err := zb.Run(input)
        if err != nil {
                t.Fatalf("❌ Execution Error: %v", err)
        }

        if len(out) > 0 && out[0] == 1 {
                t.Log("✅ ZETA-Ω∞ GIGA-BATCH: VERIFIED")
        } else {
                t.Errorf("❌ FAILED: verification returned 0 (invalid signature or parse error)")
        }
}
